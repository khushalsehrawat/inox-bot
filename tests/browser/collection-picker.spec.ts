import { test, expect } from "@playwright/test";

test("mobile collection picker searches, selects and restores focus without overflow", async ({ page }) => {
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("/products");
  const trigger = page.locator(".collection-picker-trigger");
  const dialog = page.getByRole("dialog", { name: "Find your collection." });
  await trigger.click();
  await expect(dialog).toBeVisible();
  await expect(trigger).toHaveAttribute("aria-expanded", "true");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  const bounds = await dialog.boundingBox();
  expect(bounds!.x).toBeGreaterThanOrEqual(0);
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(390);
  expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(844);
  await page.keyboard.press("Tab");
  expect(await dialog.evaluate(element => element.contains(document.activeElement))).toBeTruthy();
  const search = page.getByRole("searchbox", { name: "Search collections" });
  expect(await search.evaluate(element => getComputedStyle(element).borderTopWidth)).toBe("0px");
  expect(await page.locator(".collection-picker-search").evaluate(element => getComputedStyle(element).flexDirection)).toBe("row");
  await search.fill("no-such-collection-xyz");
  await expect(page.getByText("No collections found. Try another name.")).toBeVisible();
  await search.fill("");
  await page.screenshot({ path: "test-results/collection-picker-390.png" });
  const choice = dialog.locator(".collection-picker-group .collection-picker-option").first();
  const name = await choice.locator(".collection-picker-option-name > span").textContent();
  await choice.click();
  await expect(dialog).not.toBeVisible();
  await expect(trigger).toBeFocused();
  await expect(page.locator(".catalogue-results-heading h2")).toHaveText(name!);
  await trigger.click();
  await expect(dialog.locator(".is-selected")).toHaveAttribute("aria-pressed", "true");
  await page.keyboard.press("Escape");
  await expect(dialog).not.toBeVisible();
  await expect(trigger).toBeFocused();
  await trigger.click();
  await page.mouse.click(2, 2);
  await expect(dialog).not.toBeVisible();
  await page.setViewportSize({ width: 760, height: 1024 });
  await trigger.click();
  await expect(dialog).toBeVisible();
  expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBeTruthy();
  await page.screenshot({ path: "test-results/collection-picker-760.png" });
  await page.setViewportSize({ width: 1440, height: 900 });
  await expect(dialog).not.toBeVisible();
  await expect(trigger).not.toBeVisible();
  await expect(page.locator(".category-nav")).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.style.overflow)).not.toBe("hidden");
});
