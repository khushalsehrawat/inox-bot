import { test, expect } from "@playwright/test";
import sharp from "sharp";
test.use({ actionTimeout: 15000 });

test("admin creates a blog, publishes H2 navigation, edits, unpublishes and deletes", async ({ page, context }) => {
  test.setTimeout(180000);
  const base = process.env.WEB_UNIFIED_TEST_URL;
  test.skip(!base, "Run node scripts/test-blogs-admin.mjs for isolated storage.");
  const headers = { Origin: base! };
  await context.route("**/www.googletagmanager.com/**", route => route.abort());
  expect((await context.request.get(`${base}/api/admin/blogs`)).status()).toBe(401);
  expect((await context.request.delete(`${base}/api/admin/blogs`, { headers, data: { slug: "any-blog", version: 1 } })).status()).toBe(401);
  expect((await context.request.post(`${base}/api/admin/blogs/upload`, { headers, data: "invalid" })).status()).toBe(401);
  expect((await context.request.post(`${base}/api/admin/session`, { headers, data: { email: "website-admin@example.test", password: "Isolated-test-admin9!" } })).ok()).toBeTruthy();
  await page.goto(`${base}/admin`);
  await page.getByRole("button", { name: "Blogs", exact: true }).click();
  await page.getByRole("button", { name: "Create blog", exact: true }).click();
  await page.getByLabel("H1 heading", { exact: false }).fill("A considered kitchen test story");
  await page.getByLabel("H2 heading 1", { exact: true }).fill("Planning the space");
  await page.getByLabel("Paragraph 1", { exact: true }).fill("Start with the way your kitchen is used.\n\nThen choose practical hardware.");
  await page.getByRole("button", { name: "Add H2 & paragraph", exact: true }).click();
  await page.getByLabel("H2 heading 2", { exact: true }).fill("Planning the space");
  await page.getByLabel("Paragraph 2", { exact: true }).fill("Make room for everyday storage.");
  // A cover image is required even when saving a complete draft.
  await page.getByRole("button", { name: "Save draft", exact: true }).click();
  await expect(page.locator(".blogs-admin").getByRole("alert")).toContainText("cover image");
  const png = await sharp({ create: { width: 160, height: 100, channels: 3, background: "#b1a28b" } }).png().toBuffer();
  await page.getByLabel("Upload blog image", { exact: true }).setInputFiles({ name: "blog.png", mimeType: "image/png", buffer: png });
  await expect(page.getByAltText("Blog cover preview")).toBeVisible();
  await page.getByRole("button", { name: "Save draft", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("saved as a draft");
  const posts = (await (await context.request.get(`${base}/api/admin/blogs`)).json()).posts;
  const draft = posts.find((p: { slug: string }) => p.slug === "a-considered-kitchen-test-story");
  expect(draft.version).toBe(1);
  expect((await context.request.get(`${base}/blog/${draft.slug}`)).status()).toBe(404);
  expect((await context.request.get(`${base}${draft.image}`)).status()).toBe(404);
  expect((await context.request.post(`${base}/api/admin/blogs`, { headers: { Origin: "https://other.example" }, data: draft })).status()).toBe(403);
  expect((await context.request.post(`${base}/api/admin/blogs`, { headers, data: { ...draft, image: "https://other.example/image.png" } })).status()).toBe(422);
  await page.getByRole("button", { name: "Publish blog", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Blog published");
  await page.screenshot({ path: "test-results/blog-editor-desktop.png", fullPage: true });
  expect((await context.request.post(`${base}/api/admin/blogs`, { headers, data: draft })).status()).toBe(409);
  const article = await context.newPage();
  await article.goto(`${base}/blog`);
  await article.getByRole("heading", { name: draft.title, exact: true }).click();
  await expect(article.getByRole("heading", { level: 1 })).toHaveText(draft.title);
  await expect(article.locator(".blog-contents nav a")).toHaveCount(2);
  await expect(article.locator(".blog-body > section p")).toHaveCount(4); // Three paragraphs and the comment introduction.
  const links = article.locator(".blog-contents nav a");
  expect(await links.nth(0).getAttribute("href")).not.toBe(await links.nth(1).getAttribute("href"));
  await links.nth(1).click();
  await expect(article).toHaveURL(/#planning-the-space-2$/);
  await expect.poll(() => article.locator(".blog-article-hero img").evaluate((img: HTMLImageElement) => img.naturalWidth)).toBeGreaterThan(0);
  for (const width of [390, 1440]) {
    await article.setViewportSize({ width, height: 900 });
    expect(await article.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBeTruthy();
  }
  // Compiling a new public route in next dev can reload an existing admin tab.
  await page.goto(`${base}/admin`);
  await page.getByRole("button", { name: "Blogs", exact: true }).click();
  await page.getByRole("button").filter({ has: page.getByRole("heading", { name: draft.title, exact: true }) }).click();
  await page.getByLabel("H2 heading 2", { exact: true }).fill("Finishing touches");
  await page.getByRole("button", { name: "Move section 2 up", exact: true }).click();
  await page.getByRole("button", { name: "Update blog", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Blog published");
  await article.reload();
  await expect(article.locator(".blog-contents nav a").first()).toContainText("Finishing touches");
  await page.close();
  page = await context.newPage();
  await page.goto(`${base}/admin`, { waitUntil: "domcontentloaded" });
  await page.getByRole("button", { name: "Blogs", exact: true }).click();
  await page.getByRole("button").filter({ has: page.getByRole("heading", { name: draft.title, exact: true }) }).click();
  await expect(page.getByLabel("H2 heading 1", { exact: true })).toHaveValue("Finishing touches");
  await page.setViewportSize({ width: 390, height: 900 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBeTruthy();
  await page.screenshot({ path: "test-results/blog-editor-mobile.png", fullPage: true });
  await page.getByRole("button", { name: "Save draft", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("hidden from the website");
  expect((await context.request.delete(`${base}/api/admin/blogs`, { headers: { Origin: "https://other.example" }, data: { slug: draft.slug, version: 1 } })).status()).toBe(403);
  expect((await context.request.delete(`${base}/api/admin/blogs`, { headers, data: { slug: draft.slug, version: 1 } })).status()).toBe(409);
  page.once("dialog", dialog => dialog.dismiss());
  await page.getByRole("button", { name: "Delete blog", exact: true }).click();
  await expect(page.getByLabel("H2 heading 1", { exact: true })).toHaveValue("Finishing touches");
  page.once("dialog", dialog => dialog.accept());
  await page.getByRole("button", { name: "Delete blog", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Blog deleted");
  await page.close();
  page = await context.newPage();
  await page.goto(`${base}/admin`, { waitUntil: "domcontentloaded" });
  await page.getByRole("button", { name: "Blogs", exact: true }).click();
  await expect(page.locator(".blog-admin-card").filter({ hasText: draft.title })).toHaveCount(0);
  const remaining = (await (await context.request.get(`${base}/api/admin/blogs`)).json()).posts;
  expect(remaining.some((post: { slug: string }) => post.slug === draft.slug)).toBeFalsy();
  expect((await context.request.get(`${base}/blog/${draft.slug}`)).status()).toBe(404);
  expect((await context.request.get(`${base}${draft.image}`)).status()).toBe(404);
});
