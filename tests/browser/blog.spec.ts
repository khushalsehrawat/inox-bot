import {test,expect} from "@playwright/test";
import {readFile,readdir} from "node:fs/promises";
import {join} from "node:path";
test.use({actionTimeout:15000,reducedMotion:"reduce"});

test("blog navigation, article, mobile layout and persistent comments",async({page,context}) => {
  test.setTimeout(120000);
  const base=process.env.WEB_UNIFIED_TEST_URL;
  test.skip(!base,"Run node scripts/test-blog.mjs for isolated comment storage.");
  await page.setViewportSize({width:1440,height:1000});
  await page.goto(`${base}/blog`);
  await expect(page.locator('.desktop-nav').getByRole('link',{name:'Blog',exact:true})).toHaveAttribute('aria-current','page');
  await expect(page.locator('.blog-feature-card')).toHaveCount(11);
  await page.getByRole('link').filter({has:page.getByRole('heading',{name:'Spice Vessel Set: Rethinking How Spices Live Above Your Counter',exact:true})}).click();
  await expect(page).toHaveURL(`${base}/blog/spice-vessel-set-overhead-spice-rail`);
  await expect(page.locator('.blog-contents nav a')).toHaveCount(7);
  await expect(page.locator('meta[name="keywords"]')).toHaveAttribute('content','overhead spice vessel rail kitchen');
  await expect.poll(() => page.locator('.blog-article-hero img').evaluate((image: HTMLImageElement) => image.naturalWidth)).toBeGreaterThan(0);
  await page.goto(`${base}/blog`);
  await page.addStyleTag({content:'nextjs-portal, .skip-link { visibility: hidden !important; }'});
  await page.screenshot({path:'docs/blog-desktop.png',fullPage:true});
  await page.locator('.blog-feature-link[href="/blog/soft-close-vs-regular-hinges"]').click();
  await expect(page).toHaveURL(`${base}/blog/soft-close-vs-regular-hinges`);
  await expect(page.getByRole('heading',{level:1})).toHaveText('Soft Close vs Regular Hinges: Is the Upgrade Worth It?');
  await expect(page.locator('.blog-body > section')).toHaveCount(8);
  await expect(page.locator('.blog-body').getByRole('heading',{name:'Household Safety',exact:true})).toBeVisible();
  await page.screenshot({path:'docs/blog-article-desktop.png',fullPage:true});
  for (const width of [390,768,1024,1440]) {
    await page.setViewportSize({width,height:844});
    expect(await page.evaluate(() => document.documentElement.scrollWidth<=innerWidth+1)).toBeTruthy();
  }
  const origin={Origin:base!},url=`${base}/api/blog/comments`;
  const comment={slug:'soft-close-vs-regular-hinges',name:'Test reader',email:'reader@example.test',website:'https://example.test',comment:'A helpful look at hardware for a new kitchen.',company:''};
  expect((await context.request.post(url,{headers:{Origin:'https://other.example'},data:comment})).status()).toBe(403);
  expect((await context.request.post(url,{headers:origin,data:{...comment,slug:'missing-post'}})).status()).toBe(404);
  expect((await context.request.post(url,{headers:origin,data:{...comment,comment:''}})).status()).toBe(422);
  expect((await context.request.post(url,{headers:origin,data:{...comment,website:'javascript:alert(1)'}})).status()).toBe(422);
  expect((await context.request.post(url,{headers:origin,data:{...comment,company:'spam'}})).status()).toBe(422);
  await page.getByLabel('Comment *',{exact:true}).fill(comment.comment);
  await page.getByLabel('Name *',{exact:true}).fill(comment.name);
  await page.getByLabel('Email *',{exact:true}).fill(comment.email);
  await page.getByLabel('Website',{exact:true}).fill(comment.website);
  await page.getByRole('checkbox').check();
  await page.getByRole('button',{name:'Post comment',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('submitted for review');
  expect((await context.request.post(url,{headers:origin,data:comment})).status()).toBe(429);
  const directory=join(process.env.WEB_CATALOGUE_DATA_DIR!,'blog-comments');
  const files=await readdir(directory);
  expect(files).toHaveLength(1);
  const saved=JSON.parse(await readFile(join(directory,files[0]),'utf8'));
  expect(saved.comment).toBe(comment.comment);
  expect(saved.status).toBe('pending');
  await page.reload();
  await expect(page.getByLabel('Name *',{exact:true})).toHaveValue(comment.name);
  await expect(page.getByLabel('Email *',{exact:true})).toHaveValue(comment.email);
  await expect(page.getByLabel('Website',{exact:true})).toHaveValue(comment.website);
  await page.getByRole('checkbox').uncheck();
  await page.reload();
  await expect(page.getByLabel('Name *',{exact:true})).toHaveValue('');
  await page.addStyleTag({content:'nextjs-portal, .skip-link { visibility: hidden !important; }'});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'docs/blog-article-mobile.png',fullPage:true});
  await page.getByRole('button',{name:'Open navigation',exact:true}).click();
  await page.locator('#mobile-navigation').getByRole('link',{name:'Blog',exact:true}).click();
  await expect(page).toHaveURL(`${base}/blog`);
  await expect(page.locator('#mobile-navigation')).toBeHidden();
  expect(await page.evaluate(() => document.documentElement.scrollWidth<=innerWidth+1)).toBeTruthy();
  await page.screenshot({path:'docs/blog-mobile.png',fullPage:true});
  expect((await context.request.get(`${base}/blog/not-a-real-post`)).status()).toBe(404);
});
