import { test, expect } from "@playwright/test";
import sharp from "sharp";
test.use({ actionTimeout: 15000 });

test("event admin saves details, uploads, cover, photo order and removals to the homepage", async ({page, context}) => {
  test.setTimeout(180000);
  const base = process.env.WEB_UNIFIED_TEST_URL;
  test.skip(!base, "Run node scripts/test-events-admin.mjs for isolated storage and credentials.");
  const origin = {Origin: base!};
  expect((await context.request.get(`${base}/api/admin/events`)).status()).toBe(401);
  expect((await context.request.post(`${base}/api/admin/events`,{headers:origin,data:{}})).status()).toBe(401);
  expect((await context.request.post(`${base}/api/admin/events/upload`,{headers:origin,data:"invalid"})).status()).toBe(401);
  const login = await context.request.post(`${base}/api/admin/session`,{headers:origin,data:{email:"website-admin@example.test",password:"Isolated-test-admin9!"}});
  expect(login.ok()).toBeTruthy();
  const initial = (await (await context.request.get(`${base}/api/admin/events`)).json()).albums;
  expect(initial).toHaveLength(6);
  const png = await sharp({create:{width:120,height:80,channels:3,background:"#ae8957"}}).png().toBuffer();
  await page.goto(`${base}/admin`);
  await page.getByRole("button",{name:"Events",exact:true}).click();
  await page.locator('.event-admin-album').nth(3).click();
  await page.getByLabel("Event title",{exact:true}).fill("Material discoveries - updated");
  await page.getByLabel("Event details",{exact:true}).fill("Updated event information saved through the admin panel.");
  await page.getByLabel(/Add gallery photos/).setInputFiles({name:"new-event-photo.png",mimeType:"image/png",buffer:png});
  await expect(page.getByRole("status")).toContainText("Photos uploaded");
  const last = page.locator('.event-admin-photo').last();
  await last.getByLabel("Image description").fill("Uploaded event sample");
  await last.getByRole("button",{name:"Use as cover",exact:true}).click();
  await last.getByRole("button",{name:"Earlier",exact:true}).click();
  await page.getByRole("button",{name:"Save event",exact:true}).click();
  await expect(page.getByRole("status")).toContainText("Event saved");
  const saved = (await (await context.request.get(`${base}/api/admin/events`)).json()).albums[3];
  expect(saved.title).toBe("Material discoveries - updated");
  expect(saved.photos).toHaveLength(13);
  expect(saved.photos[11].src).toBe(saved.cover.src);
  expect(saved.version).toBe(2);
  expect((await context.request.get(`${base}${saved.cover.src}`)).status()).toBe(200);
  expect((await context.request.post(`${base}/api/admin/events`,{headers:origin,data:initial[3]})).status()).toBe(409);
  expect((await context.request.post(`${base}/api/admin/events`,{headers:{Origin:"https://other.example"},data:saved})).status()).toBe(403);
  expect((await context.request.post(`${base}/api/admin/events`,{headers:origin,data:{...saved,photos:[]}})).status()).toBe(422);
  expect((await context.request.post(`${base}/api/admin/events`,{headers:origin,data:{...saved,photos:[{...saved.cover,src:"https://other.example/photo.webp"}]}})).status()).toBe(422);
  const other = await context.newPage();
  await other.goto(base!);
  const card = other.locator('.journal-card').nth(3);
  await expect(card).toContainText(saved.title);
  await expect(card.locator('img')).toHaveAttribute('src',saved.cover.src);
  await card.click();
  await expect(other.getByRole('dialog').getByRole('heading')).toHaveText(saved.title);
  await expect(other.locator('.event-gallery-grid button')).toHaveCount(13);
  await other.close();
  await page.reload();
  await page.getByRole('button',{name:'Events',exact:true}).click();
  await page.locator('.event-admin-album').nth(3).click();
  await expect(page.getByLabel('Event title',{exact:true})).toHaveValue(saved.title);
  await page.locator('.event-admin-photo').nth(11).getByLabel('Replace photo').setInputFiles({name:'replacement.png',mimeType:'image/png',buffer:png});
  await expect(page.getByRole('status')).toContainText('Photos uploaded');
  await page.getByRole('button',{name:'Save event',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('Event saved');
  const replaced = (await (await context.request.get(`${base}/api/admin/events`)).json()).albums[3];
  expect(replaced.cover.src).not.toBe(saved.cover.src);
  expect((await context.request.get(`${base}${saved.cover.src}`)).status()).toBe(404);
  await page.locator('.event-admin-photo').nth(11).getByRole('button',{name:'Remove photo',exact:true}).click();
  await page.getByRole('button',{name:'Save event',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('Event saved');
  const removed = (await (await context.request.get(`${base}/api/admin/events`)).json()).albums[3];
  expect(removed.photos).toHaveLength(12);
  expect(removed.cover.src).toBe(removed.photos[0].src);
  expect((await context.request.get(`${base}${replaced.cover.src}`)).status()).toBe(404);
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'docs/events-admin-mobile.png',fullPage:true});
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth+1)).toBeTruthy();
});
